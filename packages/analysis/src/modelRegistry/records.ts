/** TotalSegmentator açık görevi (henüz uygulamaya alınmamış). */
function tsTask(o: {
  id: string;
  task: string;
  name: string;
  dataset: string;
  release: string;
  bytes: number;
  modality: Array<'CT' | 'MRI'>;
  grid: string;
  classes: string;
  status: 'AVAILABLE' | 'HEAVY_RUNTIME';
  reason: string;
  recheck?: ModelResearchRecord['recheck'];
}): ModelResearchRecord {
  return {
    id: o.id,
    name: o.name,
    family: 'TotalSegmentator',
    officialRepository: TS_REPO,
    weightsUrl: `${TS_REL}/${o.release}/${o.dataset}.zip`,
    weightsBytes: o.bytes,
    version: `${o.release} · ${o.dataset.split('_')[0]} (görev '${o.task}')`,
    checksum: null,
    modality: o.modality,
    inputFormat: `DICOM serisi / NIfTI → ${o.grid} ızgara`,
    outputFormat: `3B etiket hacmi: ${o.classes}`,
    task: o.task,
    capabilities: SEG3D,
    runtime: { ...NNUNET, onnxPossible: true },
    license: APACHE_TS,
    status: o.status,
    verified: false,
    verificationDate: null,
    evidence: `Resmi görev kaydında var; ağırlık dosyası bu ortamdan indirilebilir (HTTP 200, ${(o.bytes / 1e6).toFixed(0)} MB). Mimari, uygulamadaki nnU-Net → ONNX dönüştürücüsüyle uyumlu (PlainConvUNet).`,
    failureReason: o.reason,
    sourcesChecked: TS_SOURCES,
    distribution: 'not-distributed',
    ...(o.recheck ? { recheck: o.recheck } : {}),
  };
}

function monai(o: {
  id: string;
  bundle: string;
  name: string;
  version: string;
  /** NGC sürümünün SHA-1 özeti; yalnızca Hugging Face'te yayımlanan sürümde null. */
  sha1: string | null;
  modality: ModelResearchRecord['modality'];
  task: string;
  input: string;
  output: string;
  capabilities: ModelResearchRecord['capabilities'];
  license: ModelResearchRecord['license'];
  status?: 'AVAILABLE' | 'RESEARCH_ONLY';
  weightsHost: 'NVIDIA CDN' | 'Google Drive';
  note?: string;
  recheck?: ModelResearchRecord['recheck'];
}): ModelResearchRecord {
  const blocked = o.weightsHost === 'Google Drive' ? ['drive.google.com', 'huggingface.co', 'api.ngc.nvidia.com'] : ['developer.download.nvidia.com', 'huggingface.co', 'api.ngc.nvidia.com'];
  return {
    id: o.id,
    name: o.name,
    family: 'MONAI Model Zoo',
    officialRepository: `github.com/Project-MONAI/model-zoo/tree/dev/models/${o.bundle}`,
    weightsUrl: o.sha1 ? `api.ngc.nvidia.com/v2/models/nvidia/monaihosting/${o.bundle.toLowerCase()}/versions/${o.version}/files/${o.bundle}_v${o.version}.zip` : `huggingface.co/MONAI/${o.bundle}/tree/${o.version}`,
    version: `${o.bundle} v${o.version}`,
    checksum: o.sha1 ? `sha1:${o.sha1}` : null,
    modality: o.modality,
    inputFormat: o.input,
    outputFormat: o.output,
    task: o.task,
    capabilities: o.capabilities,
    runtime: MONAI_RT,
    license: o.license,
    status: o.status ?? 'AVAILABLE',
    verified: false,
    verificationDate: null,
    evidence: `MONAI kataloğunda sürümlü paket ve özet var (v${o.version}); ağırlık ${o.weightsHost} üzerinde (large_files.yml).${o.note ? ` ${o.note}` : ''}`,
    failureReason: `Ağırlık bu derleme ortamından indirilemedi (${blocked.join(', ')} engelli); indirilip SHA ve resmi çıktıyla doğrulanmadan uygulamaya alınmaz. Sonra: ağı açık bir makinede paketi indir → TorchScript/ONNX'e çevir → aynı girdide MONAI çıktısıyla karşılaştır → "Model kur" paketi.`,
    sourcesChecked: MONAI_SOURCES,
    blockedHosts: blocked,
    distribution: 'not-distributed',
    ...(o.recheck ? { recheck: o.recheck } : {}),
  };
}

